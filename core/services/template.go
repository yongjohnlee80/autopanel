// Package services deploys services from templates: a TURN relay first. A
// service runs under rootless Podman as its own unprivileged user, as a
// systemd unit of that user, and gets what its template grants: its ports,
// its own directory, a memory limit, and no capability.
//
// A template is Go, compiled in. It is reviewed as code and cannot be
// supplied at run time: no verb takes an image, a command or a path.
package services

import (
	"errors"
	"io/fs"
	"regexp"
	"sort"
	"strconv"
	"strings"

	"github.com/yongjohnlee80/autopanel/core/gate"
)

// Kind is what an option's value must be.
type Kind string

const (
	HostName  Kind = "host"       // a DNS name, made canonical
	Port      Kind = "port"       // 1024 to 65535: a service's user cannot bind a lower one
	PortRange Kind = "port_range" // "49152-49999", both ends as Port, at most MaxRange ports
	Int       Kind = "int"
	Bool      Kind = "bool" // "true" or "false"
	Choice    Kind = "choice"
)

// MaxRange bounds a port range: a relay needs hundreds of ports, never tens
// of thousands.
const MaxRange = 4096

// Option is one field of a template's deploy form.
type Option struct {
	Key     string   `json:"key"`               // "realm"
	Label   string   `json:"label"`             // a message id, for the panel
	Kind    Kind     `json:"kind"`              //
	Default string   `json:"default,omitempty"` // "" with no default: the option is required
	Choices []string `json:"choices,omitempty"` // for Choice
}

// Network is how a service's container reaches the network.
type Network string

const (
	// Private is a network of the container's own: only the ports the
	// template names are published. The default.
	Private Network = "private"
	// HostNetwork is the host's own network. A template that takes it says
	// why, where it does.
	HostNetwork Network = "host"
)

// PortUse is a port, or a range of ports, a service listens on.
type PortUse struct {
	Proto string `json:"proto"` // "tcp" or "udp"
	From  int    `json:"from"`
	To    int    `json:"to"` // the same as From for one port
}

// File is a file a template renders into the service's directory.
type File struct {
	Path string      // relative to the service's directory: "config/turnserver.conf"
	Mode fs.FileMode // 0400 for what holds a secret
	Body []byte
}

// Template is a kind of service.
type Template struct {
	Name    string   // "turn": also the default service name
	Title   string   // a message id, for the panel
	Image   string   // pinned by digest
	Options []Option // what the deploy form asks
	Network Network
	Ports   func(v Values) []PortUse
	// Secrets are generated by the core when the service is first deployed,
	// sealed in the store, and kept across updates.
	Secrets []string
	// Files are the configuration: rendered again on every deploy and update.
	Files func(v Values, secrets map[string]string) []File
	// Mounts are directories of the service's own, each mounted read-only in
	// the container: "config" → "/etc/coturn".
	Mounts map[string]string
	Args   func(v Values) []string // the container's command line
	Memory string                  // the unit's MemoryMax: "128M"
}

// Values are a template's options, validated.
type Values struct{ raw map[string]string }

// Raw is the values as they are stored.
func (v Values) Raw() map[string]string {
	out := make(map[string]string, len(v.raw))
	for k, s := range v.raw {
		out[k] = s
	}
	return out
}

// Get is the value of key.
func (v Values) Get(key string) string { return v.raw[key] }

// Port is the port option key.
func (v Values) Port(key string) int {
	n, _ := strconv.Atoi(v.raw[key])
	return n
}

// Range is the port range option key.
func (v Values) Range(key string) (from, to int) {
	a, b, _ := strings.Cut(v.raw[key], "-")
	from, _ = strconv.Atoi(a)
	to, _ = strconv.Atoi(b)
	return from, to
}

// ErrBadOption is an option the template does not take, a missing one with no
// default, or a value its kind refuses. The error wrapping it names the key.
var ErrBadOption = errors.New("services: a bad option")

// OptionError is ErrBadOption for one option. Its key is the template's own,
// or the caller's quoted and cut short; its reason is a constant.
type OptionError struct{ Key, Why string }

func (e *OptionError) Error() string        { return "services: option " + e.Key + ": " + e.Why }
func (e *OptionError) Is(target error) bool { return target == ErrBadOption }

// PublicDetail is what a client is told beyond the error's own message.
func (e *OptionError) PublicDetail() string { return e.Key + ": " + e.Why }

func badOption(key, why string) error { return &OptionError{Key: key, Why: why} }

func port(s string) (int, bool) {
	n, err := strconv.Atoi(s)
	return n, err == nil && n >= 1024 && n <= 65535 && strconv.Itoa(n) == s
}

// check is s as kind keeps it, or why it is refused.
func (o Option) check(s string) (string, error) {
	switch o.Kind {
	case HostName:
		h, err := gate.CanonicalHost(s)
		if err != nil {
			return "", badOption(o.Key, "not a valid host name")
		}
		return h, nil
	case Port:
		if _, ok := port(s); !ok {
			return "", badOption(o.Key, "a port is a number from 1024 to 65535")
		}
	case PortRange:
		a, b, cut := strings.Cut(s, "-")
		from, ok1 := port(a)
		to, ok2 := port(b)
		switch {
		case !cut || !ok1 || !ok2 || from > to:
			return "", badOption(o.Key, "a port range is first-last, each from 1024 to 65535")
		case to-from+1 > MaxRange:
			return "", badOption(o.Key, "a port range holds at most "+strconv.Itoa(MaxRange)+" ports")
		}
	case Int:
		if n, err := strconv.Atoi(s); err != nil || strconv.Itoa(n) != s {
			return "", badOption(o.Key, "not a whole number")
		}
	case Bool:
		if s != "true" && s != "false" {
			return "", badOption(o.Key, "true or false")
		}
	case Choice:
		for _, c := range o.Choices {
			if c == s {
				return s, nil
			}
		}
		return "", badOption(o.Key, "one of "+strings.Join(o.Choices, ", "))
	default:
		return "", badOption(o.Key, "the template names no kind for it")
	}
	return s, nil
}

// Validate reads raw against the template's options. An unknown key, a missing
// option with no default, and a value its kind refuses are each an error that
// names the key. Two options may not claim one port.
func (t Template) Validate(raw map[string]string) (Values, error) {
	known := map[string]bool{}
	out := map[string]string{}
	for _, o := range t.Options {
		known[o.Key] = true
		s, ok := raw[o.Key]
		if !ok || s == "" {
			s = o.Default
		}
		if s == "" {
			return Values{}, badOption(o.Key, "required")
		}
		s, err := o.check(s)
		if err != nil {
			return Values{}, err
		}
		out[o.Key] = s
	}
	var unknown []string
	for k := range raw {
		if !known[k] {
			unknown = append(unknown, k)
		}
	}
	if len(unknown) > 0 {
		sort.Strings(unknown)
		k := unknown[0]
		if len(k) > 32 {
			k = k[:32]
		}
		return Values{}, badOption(strconv.QuoteToASCII(k), "the template has no such option")
	}
	v := Values{raw: out}
	if t.Ports != nil {
		if err := distinct(t.Ports(v)); err != nil {
			return Values{}, err
		}
	}
	return v, nil
}

// distinct refuses two uses of one port and protocol.
func distinct(ports []PortUse) error {
	for i, a := range ports {
		for _, b := range ports[i+1:] {
			if a.Proto == b.Proto && a.From <= b.To && b.From <= a.To {
				return badOption(a.Proto+" port "+strconv.Itoa(max(a.From, b.From)), "two options claim it")
			}
		}
	}
	return nil
}

// nameRE is a service's name: it is also part of its user's name ("ap-" and
// the name, 32 characters at most) and of its unit's file name.
var nameRE = regexp.MustCompile(`^[a-z][a-z0-9-]{0,28}$`)

// ErrBadName is a service name that is not a lower-case letter followed by
// letters, digits and hyphens, 29 characters at most.
var ErrBadName = errors.New("services: a bad service name")

// ValidName reports whether name can be a service's.
func ValidName(name string) bool { return nameRE.MatchString(name) }

// UserOf is the host user a service runs as.
func UserOf(name string) string { return "ap-" + name }
