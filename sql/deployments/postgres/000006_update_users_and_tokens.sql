-- 000006: users with roles, their second factor, the lockout, and API tokens.
-- The SQLite engine's 000006, translated as 000001 is.

ALTER TABLE app_user ADD COLUMN role text COLLATE "C" NOT NULL DEFAULT 'admin';
ALTER TABLE app_user ADD COLUMN verifier text COLLATE "C" NOT NULL DEFAULT '';
ALTER TABLE app_user ADD COLUMN must_change integer NOT NULL DEFAULT 0;
ALTER TABLE app_user ADD COLUMN disabled_at bigint NOT NULL DEFAULT 0;
ALTER TABLE app_user ADD COLUMN locked_until bigint NOT NULL DEFAULT 0;
ALTER TABLE app_user ADD COLUMN fail_count integer NOT NULL DEFAULT 0;
ALTER TABLE app_user ADD COLUMN last_login_at bigint NOT NULL DEFAULT 0;
ALTER TABLE app_user ADD COLUMN totp integer NOT NULL DEFAULT 0;
ALTER TABLE app_user ADD COLUMN totp_last_step bigint NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS recovery_code (
  user_id bigint NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
  hash    bytea NOT NULL,
  PRIMARY KEY (user_id, hash)
);

CREATE TABLE IF NOT EXISTS api_token (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id      bigint NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
  name         text COLLATE "C" NOT NULL,
  hash         bytea NOT NULL UNIQUE,
  role         text COLLATE "C" NOT NULL,
  created_at   bigint NOT NULL,
  expires_at   bigint NOT NULL,
  last_used_at bigint NOT NULL DEFAULT 0,
  revoked_at   bigint NOT NULL DEFAULT 0,
  CHECK (name <> ''),
  CHECK (role IN ('admin', 'operator', 'mail', 'viewer'))
);
